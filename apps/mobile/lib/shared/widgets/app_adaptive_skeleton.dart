/// ─────────────────────────────────────────────────────────────────────────────
/// ADHOCX UNIVERSAL ADAPTIVE SKELETON LOADING ENGINE
/// ─────────────────────────────────────────────────────────────────────────────
/// The single, centralized adaptive skeleton loader for the entire application.
///
/// Rather than writing boilerplate placeholder widgets for individual screens,
/// [AdaptiveSkeleton] automatically scans the render-object tree of [child],
/// transforming Text, Icons, Avatars, Cards, and Badges into synchronized,
/// shimmering bone shapes matching the exact geometry of the live UI.
///
/// Features:
/// • Zero cumulative layout shift (CLS): skeleton matches the exact real layout.
/// • Light / Dark operational mode awareness (deep slate base with luminous waves).
/// • Smooth 300ms cross-fade transition from skeleton to live data.
/// • [AdaptiveSkeleton.repeat] for dynamic lists where data is empty during loading.
/// • [AdaptiveSkeleton.sliver] for [CustomScrollView] and sliver trees.
/// • [AdaptiveSkeleton.ignore] / [AdaptiveSkeleton.keep] for selective bone filtering.
class AdaptiveSkeleton extends StatelessWidget {
  /// Whether the skeleton effect is active.
  final bool isLoading;

  /// The target widget layout to skeletonize.
  final Widget child;

  /// Whether container decorations (backgrounds/borders) are ignored. Default is false.
  final bool ignoreContainers;

  /// Duration of the transition fade when switching from skeleton to loaded content.
  final Duration switchDuration;

  /// Duration for one complete shimmer wave across the screen.
  final Duration shimmerDuration;

  const AdaptiveSkeleton({
    super.key,
    required this.isLoading,
    required this.child,
    this.ignoreContainers = false,
    this.switchDuration = const Duration(milliseconds: 300),
    this.shimmerDuration = const Duration(milliseconds: 1400),
  });

  /// Specialized constructor for dynamic lists/feeds where the initial data
  /// array is empty (`itemCount == 0`).
  ///
  /// While [isLoading] is true, renders [mockCount] instances generated by
  /// [mockBuilder] automatically morphed into shimmering skeleton cards.
  /// Once [isLoading] turns false, smoothly cross-fades into [child].
  static Widget repeat({
    Key? key,
    required bool isLoading,
    required int mockCount,
    required Widget Function(BuildContext context, int index) mockBuilder,
    required Widget child,
    Widget? separator,
    EdgeInsetsGeometry padding = EdgeInsets.zero,
    Axis scrollDirection = Axis.vertical,
    bool ignoreContainers = false,
  }) {
    return _AdaptiveSkeletonRepeat(
      key: key,
      isLoading: isLoading,
      mockCount: mockCount,
      mockBuilder: mockBuilder,
      separator: separator,
      padding: padding,
      scrollDirection: scrollDirection,
      ignoreContainers: ignoreContainers,
      child: child,
    );
  }

  /// Specialized constructor for sliver-based scroll views ([CustomScrollView]).
  static Widget sliver({
    Key? key,
    required bool isLoading,
    required Widget child,
    bool ignoreContainers = false,
    Duration switchDuration = const Duration(milliseconds: 300),
  }) {
    return _AdaptiveSkeletonSliver(
      key: key,
      isLoading: isLoading,
      ignoreContainers: ignoreContainers,
      switchDuration: switchDuration,
      child: child,
    );
  }

  /// Exclude a widget subtree from being converted to skeleton bones.
  /// The widget remains fully visible and interactive.
  static Widget ignore({required Widget child}) => Skeleton.ignore(child: child);

  /// Keep the child painted with its normal color/styling even while skeleton is active.
  static Widget keep({required Widget child}) => Skeleton.keep(child: child);

  /// Treat a widget as a unified leaf bone without recursing into its children.
  static Widget leaf({required Widget child}) => Skeleton.leaf(child: child);

  /// Standalone bone pill for granular layout compositions.
  static Widget bone({
    double? width,
    required double height,
    double borderRadius = AppRadius.md,
  }) {
    return Bone(
      width: width,
      height: height,
      borderRadius: BorderRadius.circular(borderRadius),
    );
  }

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;

    return Skeletonizer(
      enabled: isLoading,
      enableSwitchAnimation: true,
      switchAnimationConfig: SwitchAnimationConfig(
        duration: switchDuration,
        switchInCurve: Curves.easeIn,
        switchOutCurve: Curves.easeOut,
      ),
      ignoreContainers: ignoreContainers,
      effect: isDark
          ? ShimmerEffect(
              baseColor: AppColors.slate800,
              highlightColor: AppColors.slate700,
              duration: shimmerDuration,
            )
          : ShimmerEffect(
              baseColor: AppColors.slate200,
              highlightColor: AppColors.slate50,
              duration: shimmerDuration,
            ),
      textBoneBorderRadius: const TextBoneBorderRadius(
        BorderRadius.all(Radius.circular(AppRadius.sm)),
      ),
      child: child,
    );
  }
}

/// Internal implementation for [AdaptiveSkeleton.repeat].
class _AdaptiveSkeletonRepeat extends StatelessWidget {
  final bool isLoading;
  final int mockCount;
  final Widget Function(BuildContext context, int index) mockBuilder;
  final Widget child;
  final Widget? separator;
  final EdgeInsetsGeometry padding;
  final Axis scrollDirection;
  final bool ignoreContainers;

  const _AdaptiveSkeletonRepeat({
    super.key,
    required this.isLoading,
    required this.mockCount,
    required this.mockBuilder,
    required this.child,
    this.separator,
    this.padding = EdgeInsets.zero,
    this.scrollDirection = Axis.vertical,
    this.ignoreContainers = false,
  });

  @override
  Widget build(BuildContext context) {
    if (!isLoading) {
      return child;
    }

    final isDark = Theme.of(context).brightness == Brightness.dark;

    final mockList = ListView.separated(
      shrinkWrap: true,
      physics: const NeverScrollableScrollPhysics(),
      padding: padding,
      scrollDirection: scrollDirection,
      itemCount: mockCount,
      separatorBuilder: (ctx, idx) => separator ?? const SizedBox(height: 12),
      itemBuilder: (ctx, idx) => mockBuilder(ctx, idx),
    );

    return Skeletonizer(
      enabled: true,
      enableSwitchAnimation: true,
      ignoreContainers: ignoreContainers,
      effect: isDark
          ? const ShimmerEffect(
              baseColor: AppColors.slate800,
              highlightColor: AppColors.slate700,
              duration: Duration(milliseconds: 1400),
            )
          : const ShimmerEffect(
              baseColor: AppColors.slate200,
              highlightColor: AppColors.slate50,
              duration: Duration(milliseconds: 1400),
            ),
      textBoneBorderRadius: const TextBoneBorderRadius(
        BorderRadius.all(Radius.circular(AppRadius.sm)),
      ),
      child: mockList,
    );
  }
}

/// Internal implementation for [AdaptiveSkeleton.sliver].
class _AdaptiveSkeletonSliver extends StatelessWidget {
  final bool isLoading;
  final Widget child;
  final bool ignoreContainers;
  final Duration switchDuration;

  const _AdaptiveSkeletonSliver({
    super.key,
    required this.isLoading,
    required this.child,
    this.ignoreContainers = false,
    this.switchDuration = const Duration(milliseconds: 300),
  });

  @override
